CREATE INDEX IF NOT EXISTS idx_find_year ON financial_indicators(year);

-- 4. Income Statements
CREATE TABLE IF NOT EXISTS financial_income_statements (
    symbol TEXT,
    year INT,
    gross_revenue FLOAT,
    net_revenue FLOAT,
    cogs FLOAT,
    gross_profit FLOAT,
    financial_income FLOAT,
    financial_expense FLOAT,
    interest_expense FLOAT,
    selling_expense FLOAT,
    admin_expense FLOAT,
    operating_profit FLOAT,
    profit_before_tax FLOAT,
    income_tax_expense FLOAT,
    net_profit_after_tax FLOAT,
    net_income_parent FLOAT,
    eps_basic FLOAT,
    ebit FLOAT,
    ebitda FLOAT,
    PRIMARY KEY (symbol, year)
);

CREATE INDEX IF NOT EXISTS idx_fis_year ON financial_income_statements(year);

-- 5. Stock Prices (15-minute intervals)
CREATE TABLE IF NOT EXISTS stock_prices_15m (
    symbol TEXT,
    trading_time TIMESTAMP WITH TIME ZONE,
    open FLOAT,
    high FLOAT,
    low FLOAT,
    close FLOAT,
    volume FLOAT,
    PRIMARY KEY (symbol, trading_time)
);

CREATE INDEX IF NOT EXISTS idx_stock_prices_15m_symbol_time ON stock_prices_15m(symbol, trading_time DESC);

-- 6. Stock Prices (1-hour intervals)
CREATE TABLE IF NOT EXISTS stock_prices_1h (
    symbol TEXT,
    trading_time TIMESTAMP WITH TIME ZONE,
    open FLOAT,
    high FLOAT,
    low FLOAT,
    close FLOAT,
    volume FLOAT,
    PRIMARY KEY (symbol, trading_time)
);

CREATE INDEX IF NOT EXISTS idx_stock_prices_1h_symbol_time ON stock_prices_1h(symbol, trading_time DESC);

-- 7. Stock Prices (1-day intervals)
CREATE TABLE IF NOT EXISTS stock_prices_1d (
    symbol TEXT,
    trading_time TIMESTAMP WITH TIME ZONE,
    open FLOAT,
    high FLOAT,
    low FLOAT,
    close FLOAT,
    volume FLOAT,
    PRIMARY KEY (symbol, trading_time)
);

CREATE INDEX IF NOT EXISTS idx_stock_prices_1d_symbol_time ON stock_prices_1d(symbol, trading_time DESC);

-- 8. Fundamental Analysis Summary (latest generated by AI)
CREATE TABLE IF NOT EXISTS fundamental_analysis_summary (
    symbol TEXT PRIMARY KEY,
    summary TEXT
);

CREATE INDEX IF NOT EXISTS idx_fundamental_analysis_summary_symbol
ON fundamental_analysis_summary(symbol);



