    financial_leverage FLOAT,
    roic FLOAT,
    interest_coverage FLOAT,
    fixed_asset_turnover FLOAT,
    -- Bank-only (credit institution) indicators; NULL for non-bank symbols.
    casa_ratio FLOAT,
