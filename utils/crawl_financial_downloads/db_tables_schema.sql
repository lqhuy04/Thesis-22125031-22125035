    shares_outstanding FLOAT,
    ev_ebitda FLOAT,
    bvps FLOAT,
    cash_ratio FLOAT,
    debt_to_equity FLOAT,
    roe FLOAT,
    roa FLOAT,
    days_receivable FLOAT,
    days_inventory FLOAT,
    quick_ratio FLOAT,
    days_payable FLOAT,
    gross_margin FLOAT,
    ebit_margin FLOAT,
    net_margin FLOAT,
